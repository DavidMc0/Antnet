#!/usr/bin/env node
// Build the archives to publish on mainnet for M2–M5 into publish/, with a README listing
// each file's size, SHA-256 and purpose.  node tools/prepare-publish.mjs

import { createHash } from "node:crypto";
import { mkdir, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { packFiles, readDir } from "./tar-writer.mjs";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const OUT = join(ROOT, "publish");
const enc = new TextEncoder();
const dec = new TextDecoder();
const sha256 = (b) => createHash("sha256").update(b).digest("hex");

// Overwrite only the files written here; never clear the folder, which may hold the
// pointer owner key (site.key) and its backup.
await mkdir(OUT, { recursive: true });
const rows = [];

async function emit(file, bytes, milestone, purpose) {
  await writeFile(join(OUT, file), bytes);
  rows.push({ file, bytes: bytes.length, sha: sha256(bytes), milestone, purpose });
}

// The SPA fixture, stamped with a visible version so a pointer update (M3) is observable.
async function spa(version) {
  const files = await readDir(join(ROOT, "fixtures", "spa"));
  const html = dec
    .decode(files.get("index.html"))
    .replace("<title>SPA fixture</title>", `<title>Loader test SPA v${version}</title>`)
    .replace(
      '<main id="view"></main>',
      `<p id="version" data-version="${version}">Version ${version}</p>\n    <main id="view"></main>`,
    );
  files.set("index.html", enc.encode(html));
  files.set(
    ".autonomi-site.json",
    enc.encode(
      JSON.stringify(
        {
          format: "autonomi-site/1",
          title: `Loader test SPA v${version}`,
          spa: true,
          headers: { "/*": { "Content-Security-Policy": "default-src 'self'; script-src 'self'" } },
        },
        null,
        2,
      ) + "\n",
    ),
  );
  return packFiles(files);
}

await emit("spa-v1.tar", await spa(1), "M2", "The SPA to open from mainnet by its i… link (M2 done-when).");
await emit("spa-v2.tar", await spa(2), "M3", "Same SPA showing “Version 2”: re-point the pointer here to test updates.");
await emit(
  "not-a-site.txt",
  enc.encode("This public file is plain text, not a tar archive. The loader must say \"Not a site archive\".\n".repeat(8)),
  "M2",
  "A public file that isn't a tar (M2 acceptance test).",
);

// Benchmark sites for the measurements in spec 11.5: an index page plus incompressible data.
function noise(n, seed) {
  const out = new Uint8Array(n);
  let block = createHash("sha256").update(seed).digest();
  for (let i = 0; i < n; i += 32) {
    out.set(block.subarray(0, Math.min(32, n - i)), i);
    block = createHash("sha256").update(block).digest();
  }
  return out;
}
for (const [label, mb] of [["0.3mb", 0.3], ["2mb", 2], ["10mb", 10]]) {
  const size = Math.round(mb * 1000 * 1000) - 4096; // leave room for headers and the page
  const files = new Map([
    [
      "index.html",
      enc.encode(
        `<!doctype html>\n<html lang="en"><head><meta charset="utf-8"><title>Loader bench ${label}</title></head>\n` +
          `<body data-bench="${label}"><h1>Loader benchmark site (${label})</h1>\n` +
          `<p>This site carries ${size} bytes of filler in <a href="/data.bin">data.bin</a> to measure open times.</p></body></html>\n`,
      ),
    ],
    ["data.bin", noise(size, `bench-${label}`)],
  ]);
  await emit(`bench-${label}.tar`, packFiles(files), "M5", `Benchmark site, ${label} (spec 11.5 measurements).`);
}

const fmt = (n) => (n >= 1e6 ? `${(n / 1e6).toFixed(2)} MB` : `${(n / 1e3).toFixed(1)} kB`);
const table = rows
  .map((r) => `| \`${r.file}\` | ${fmt(r.bytes)} | ${r.milestone} | ${r.purpose} |`)
  .join("\n");
const hashes = rows.map((r) => `${r.sha}  ${r.file}`).join("\n");

await writeFile(
  join(OUT, "README.md"),
  `# Files to publish on mainnet

Generated by \`node tools/prepare-publish.mjs\`. The output is deterministic: running it again gives the same bytes.

| File | Size | Needed for | Purpose |
| --- | --- | --- | --- |
${table}

Uploaded so far:

| File | Address |
| --- | --- |
| \`spa-v1.tar\` | \`9ea63625861bd3e72a31bf54af2f2e5daf9a1a1f0a04c5f5fb43d8e281a1e9e1\` |
| \`spa-v2.tar\` | \`5423f9da1e46527e28228f90553add3089f5bbd4adbc8c7c210675afbe0541b3\` |
| \`not-a-site.txt\` | \`3c58fa1efb58346a639ab423b95ec9b039c0b46179496486f880e1281cefc822\` |

## Setting the wallet key (ant CLI 0.3.13)

Commands that pay (\`file upload\`, \`pointer create\`, \`pointer update\`) read the wallet's
private key from the \`SECRET_KEY\` environment variable. How to set it depends on the shell.

**Windows PowerShell:** set it once per window; it lasts until the window closes.

\`\`\`powershell
$env:SECRET_KEY = "0x..."        # your wallet's private key
# ... run the ant commands below ...
Remove-Item Env:SECRET_KEY       # clear it when you're done
\`\`\`

**Command Prompt (cmd.exe):** \`set SECRET_KEY=0x...\` (no quotes), and \`set SECRET_KEY=\` to clear it.

**bash / Git Bash / macOS / Linux:** put it in front of each command, as in \`SECRET_KEY=0x... ant file upload ...\`.

The commands below are written for PowerShell with \`SECRET_KEY\` already set. Run them in
the folder that holds the files and \`site.key\`.

## Upload

\`\`\`powershell
ant file upload spa-v1.tar --public
ant file upload not-a-site.txt --public
\`\`\`

Each upload prints the file's address (64 hex). Send those addresses back.
\`node tools/link.mjs i <address>\` turns one into a site link.

## The pointer for M3

\`\`\`powershell
ant pointer keygen --output site.key      # once; back this up, it can't be recovered
ant pointer create --key site.key 9ea63625861bd3e72a31bf54af2f2e5daf9a1a1f0a04c5f5fb43d8e281a1e9e1
ant pointer address --key site.key        # send this address back
\`\`\`

\`pointer create\` points the new pointer at \`spa-v1.tar\`. Only \`create\` and \`update\` need
\`SECRET_KEY\`; \`keygen\` and \`address\` don't pay.

Later, during the M3 test, when asked, re-point it at \`spa-v2.tar\`:

\`\`\`powershell
ant pointer update --key site.key 5423f9da1e46527e28228f90553add3089f5bbd4adbc8c7c210675afbe0541b3
\`\`\`

## SHA-256 of each file

\`\`\`
${hashes}
\`\`\`
`,
);
console.log(`Wrote ${rows.length} files to ${OUT}`);
for (const r of rows) console.log(`  ${r.file.padEnd(16)} ${fmt(r.bytes).padStart(9)}  ${r.milestone}`);
